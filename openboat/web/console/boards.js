/* An alert sitting at the bottom of a card body brings its own margin, which the body's
   padding then doubles. Used by the three views this file is loaded ahead of. */
function obFlat(n) { n.classList.remove("mb-3"); n.classList.add("mb-0"); return n; }

/* A key/value card body. The class is what lets a value with no spaces in it — a file
   path, a Signal K source — wrap instead of widening the page on a phone. */
function obKvBody(pairs) {
  const b = cardBody(kv(pairs, null));
  b.classList.add("ob-kv");
  return b;
}

